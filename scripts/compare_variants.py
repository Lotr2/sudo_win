"""Run variants on the same briefs and decisions, write variants/<name>/scorecard.md and .planning/COMPARISON.md.

    python scripts/compare_variants.py --all --fake-llm          # structural check, < 1 minute, no Ollama
    python scripts/compare_variants.py --variant anan            # real run with Ollama
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.conventions import is_valid_output_name  # noqa: E402
from core.runner import VARIANTS_DIR, list_variants, run_variant  # noqa: E402
import guardrails  # noqa: E402

BRIEF = ROOT / "demo" / "founder_brief_idea1.md"           # idea1 (weak) -> founder pivots to idea2 (strong)
DECISIONS = ROOT / "demo" / "founder_decisions.yaml"
TRICKS = sorted(p for p in (ROOT / "evals" / "trick_prompts").glob("*.md") if p.name != "README.md")
COLUMNS = ["variant", "contract", "end_to_end", "idea1_stop", "verified_claims_pct", "guardrail_violations",
           "trick_refusals", "runtime_s", "tokens", "llm_calls", "failed_steps"]


def contract_status(name: str) -> str:
    import subprocess
    r = subprocess.run([sys.executable, "-m", "pytest", "-q", "-x", str(ROOT / "tests" / "test_variant_contract.py"),
                        "-k", name, "-p", "no:cacheprovider"], cwd=ROOT, capture_output=True, text=True)
    return "pass" if r.returncode == 0 else "FAIL"


def score(name: str, fake: bool, out_root: Path, check_contract: bool) -> dict:
    run_dir = out_root / name / ("fake" if fake else datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ"))
    if run_dir.exists():
        shutil.rmtree(run_dir)
    t0 = time.time()
    s = run_variant(name, BRIEF, DECISIONS, fake=fake, run_dir=run_dir)
    runtime = round(time.time() - t0, 1)
    outputs = Path(s["outputs_dir"])
    names = [p.name for p in outputs.iterdir()]
    violations = sum(len(guardrails.lint(p.read_text(encoding="utf-8"))) for p in outputs.iterdir())
    st = s["stats"]
    res = s["results"]
    refused = 0
    for t in TRICKS:
        tr = run_variant(name, t, None, fake=fake, run_dir=run_dir / "tricks" / t.stem)
        refused += tr["results"][0]["status"] == "refused"
    return {
        "variant": name,
        "contract": contract_status(name) if check_contract else "not checked",
        "end_to_end": "yes" if res[-1]["idea"] == "idea2" and res[-1]["status"] == "completed" else f"no ({res[-1]['status']} at phase {res[-1]['last_phase']})",
        "idea1_stop": "yes" if "phase2_gate_idea1-stop.md" in names else "no",
        "verified_claims_pct": round(100 * st["claims_verified"] / st["claims_total"], 1) if st["claims_total"] else 0.0,
        "guardrail_violations": violations,
        "trick_refusals": f"{refused}/{len(TRICKS)}",
        "runtime_s": runtime,
        "tokens": st["tokens"],
        "llm_calls": st["llm_calls"],
        "failed_steps": len(st["failed_steps"]),
        "nonstandard_outputs": [n for n in names if not is_valid_output_name(n)],
        "failed_step_ids": st["failed_steps"],
        "fake_llm": fake,
        "run_dir": str(run_dir),
    }


def write_scorecard(m: dict) -> None:
    lines = ["<!-- generated by scripts/compare_variants.py; never edit by hand -->",
             f"# Scorecard: {m['variant']}", "",
             f"_Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} · "
             f"{'FAKE LLM (structure only)' if m['fake_llm'] else 'real model run'} · same briefs and decisions for every variant_", "",
             "| metric | value |", "|---|---|"]
    lines += [f"| {c} | {m[c]} |" for c in COLUMNS[1:]]
    if m["failed_step_ids"]:
        lines += ["", "Failed steps: " + ", ".join(m["failed_step_ids"])]
    if m["nonstandard_outputs"]:
        lines += ["", "Non-standard outputs: " + ", ".join(m["nonstandard_outputs"])]
    lines += ["", f"Run directory (gitignored): `{Path(m['run_dir']).relative_to(ROOT).as_posix()}`", ""]
    (VARIANTS_DIR / m["variant"] / "scorecard.md").write_text("\n".join(lines), encoding="utf-8")


def write_comparison(rows: list[dict]) -> None:
    path = ROOT / ".planning" / "COMPARISON.md"
    path.parent.mkdir(exist_ok=True)
    old = {}
    if path.exists():   # keep rows of variants not re-run this time
        for line in path.read_text(encoding="utf-8").splitlines():
            cells = [c.strip() for c in line.strip("|").split("|")]
            if line.startswith("| ") and len(cells) == len(COLUMNS) + 2 and cells[0] not in ("variant", "---"):
                old[cells[0].strip("[]").split("](")[0].strip("[")] = line
    new = {r["variant"]: "| " + " | ".join([f"[{r['variant']}](../variants/{r['variant']}/DESIGN.md)"] +
                                            [str(r[c]) for c in COLUMNS[1:]] + ["fake" if r["fake_llm"] else "real"]) + " |"
           for r in rows}
    merged = {**old, **new}
    header = "| " + " | ".join(COLUMNS + ["llm"]) + " |"
    lines = ["<!-- generated by scripts/compare_variants.py; never edit by hand -->", "# Variant comparison", "",
             f"_Updated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. Same briefs (idea1 weak -> pivot -> idea2) "
             "and the same founder decisions file for every variant. Click a variant for its DESIGN.md._", "",
             header, "|" + "---|" * (len(COLUMNS) + 1)] + [merged[k] for k in sorted(merged)] + [""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--all", action="store_true")
    g.add_argument("--variant", action="append")
    p.add_argument("--fake-llm", action="store_true")
    p.add_argument("--no-contract", action="store_true", help="skip the per-variant contract test")
    a = p.parse_args(argv)
    names = list_variants() if a.all else a.variant
    rows = []
    for n in names:
        m = score(n, a.fake_llm, ROOT / "runs", not a.no_contract)
        write_scorecard(m)
        rows.append(m)
        print(json.dumps({c: m[c] for c in COLUMNS}))
    write_comparison(rows)
    return 0 if all(r["contract"] != "FAIL" and not r["nonstandard_outputs"] for r in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
